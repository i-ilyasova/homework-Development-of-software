// 1. Синхронный код выполняется первым — он попадает сразу в стек вызовов
console.log('1. Синхронный: начало скрипта');

// 2. setTimeout добавляет колбэк в очередь макрозадач (macrotask queue).
//    Даже с задержкой 0 мс он НЕ выполнится раньше микрозадач.
setTimeout(() => {
  console.log('5. setTimeout (0 мс) — макрозадача: выполняется последней');
}, 0);

setTimeout(() => {
  console.log('6. setTimeout (100 мс) — макрозадача: выполняется после предыдущей');
}, 100);

// 3. Promise.resolve() создаёт уже выполненный промис.
//    Его колбэк .then() попадает в очередь микрозадач (microtask queue).
//    Микрозадачи обрабатываются до следующей макрозадачи.
Promise.resolve()
  .then(() => {
    console.log('3. Promise.then (первый) — микрозадача: выполняется после синхронного кода');
  })
  .then(() => {
    // Каждый .then() добавляет новую микрозадачу в очередь
    console.log('4. Promise.then (второй) — микрозадача: добавлена предыдущим .then()');
  });

// 4. Синхронный код продолжает выполняться до конца текущего кадра
console.log('2. Синхронный: конец скрипта');

// Итоговый порядок вывода:
// 1 → 2 → 3 → 4 → 5 → 6
//
// Объяснение:
// - Весь синхронный код (1, 2) выполняется первым, так как находится в стеке вызовов.
// - После очистки стека Event Loop проверяет очередь микрозадач:
//   Promise.then — микрозадача, поэтому (3) и (4) выполняются следующими.
//   Очередь микрозадач полностью очищается перед переходом к макрозадачам.
// - Только после этого Event Loop берёт следующую макрозадачу из очереди:
//   сначала setTimeout(0) → (5), затем setTimeout(100) → (6).
